"use client";

import { useRouter } from "next/navigation";
import { useEffect, useRef, useState } from "react";
import { createClient } from "@/lib/supabase/client";

type Step =
  | { kind: "loading" }
  | { kind: "enroll"; factorId: string; qrCode: string; secret: string }
  | { kind: "verify"; factorId: string }
  | { kind: "error"; message: string };

/**
 * Second sign-in step. First visit: enrol an authenticator app (QR code + manual secret).
 * Later visits: enter the current 6-digit code. Success upgrades the session to aal2.
 */
export default function MfaPage() {
  const router = useRouter();
  const [step, setStep] = useState<Step>({ kind: "loading" });
  const [codeError, setCodeError] = useState<string | null>(null);
  const started = useRef(false);

  useEffect(() => {
    if (started.current) return; // React dev mode runs effects twice; enrol only once
    started.current = true;

    (async () => {
      const mfa = createClient().auth.mfa;
      const { data, error } = await mfa.listFactors();
      if (error) return setStep({ kind: "error", message: error.message });

      const verified = data.totp[0];
      if (verified) return setStep({ kind: "verify", factorId: verified.id });

      // An abandoned enrolment leaves an unverified factor that would block a new one.
      for (const stale of data.all.filter((f) => f.factor_type === "totp")) {
        await mfa.unenroll({ factorId: stale.id });
      }
      const enrolled = await mfa.enroll({ factorType: "totp", friendlyName: "Authenticator app" });
      if (enrolled.error) return setStep({ kind: "error", message: enrolled.error.message });
      setStep({
        kind: "enroll",
        factorId: enrolled.data.id,
        qrCode: enrolled.data.totp.qr_code,
        secret: enrolled.data.totp.secret,
      });
    })();
  }, []);

  async function submitCode(form: FormData) {
    if (step.kind !== "enroll" && step.kind !== "verify") return;
    setCodeError(null);
    const { error } = await createClient().auth.mfa.challengeAndVerify({
      factorId: step.factorId,
      code: String(form.get("code")).trim(),
    });
    if (error) return setCodeError(error.message);
    router.replace("/");
    router.refresh();
  }

  return (
    <main className="mx-auto mt-24 w-full max-w-sm px-4">
      <h1 className="mb-6 text-2xl font-semibold">Two-factor authentication</h1>

      {step.kind === "loading" && <p>Loading…</p>}
      {step.kind === "error" && <p role="alert" className="text-red-600">{step.message}</p>}

      {step.kind === "enroll" && (
        <div className="mb-4 flex flex-col gap-2 text-sm">
          <p>Scan this with your authenticator app, then enter the 6-digit code it shows.</p>
          {/* qr_code is an SVG data URL generated by Supabase Auth */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={step.qrCode} alt="Authenticator QR code" width={180} height={180} />
          <p>
            Can&apos;t scan? Enter this key: <code data-testid="totp-secret">{step.secret}</code>
          </p>
        </div>
      )}

      {(step.kind === "enroll" || step.kind === "verify") && (
        <form action={submitCode} className="flex flex-col gap-3">
          <label className="flex flex-col gap-1 text-sm">
            Code
            <input
              name="code"
              inputMode="numeric"
              pattern="[0-9]{6}"
              maxLength={6}
              required
              autoComplete="one-time-code"
              className="rounded border px-3 py-2"
            />
          </label>
          {codeError && <p role="alert" className="text-sm text-red-600">{codeError}</p>}
          <button type="submit" className="rounded bg-foreground px-3 py-2 text-background">
            Verify
          </button>
        </form>
      )}
    </main>
  );
}
